// Generates data/routeLastModified.ts from git history: last commit date of each
// route's page files (app/<route>/ plus the legacy component it renders).
// Run: node scripts/gen-route-lastmod.mjs  (re-run and commit when pages change)
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const git = (args) => execSync(`git log -1 --format=%cI -- ${args}`, { encoding: 'utf8' }).trim();
const bridge = fs.readFileSync('components/next-bridge/LegacyClientPage.tsx', 'utf8');
const imports = Object.fromEntries([...bridge.matchAll(/import (\w+) from '@\/legacy\/([\w/]+)'/g)].map((m) => [m[1], `legacy/${m[2]}.tsx`]));
const keyToFile = Object.fromEntries([...bridge.matchAll(/(\w+): \(\) => <(\w+)/g)].map((m) => [m[1], imports[m[2]]]).filter(([, f]) => f));

const out = {};
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (e.name === 'page.tsx' && !p.includes('[')) {
      const routeDir = path.dirname(p);
      const route = '/' + path.relative('app', routeDir).split(path.sep).join('/');
      const src = fs.readFileSync(p, 'utf8');
      const files = [routeDir === 'app' ? p : routeDir];
      const key = src.match(/LegacyClientPage page="(\w+)"/)?.[1];
      if (key && keyToFile[key]) files.push(keyToFile[key]);
      for (const m of src.matchAll(/from '@\/components\/(\w+Client)'/g)) files.push(`components/${m[1]}.tsx`);
      const dates = files.map((f) => git(f)).filter(Boolean).sort((a, b) => Date.parse(a) - Date.parse(b));
      if (dates.length) out[route === '/.' || route === '/' ? '/' : route.replace(/\/$/, '')] = dates[dates.length - 1];
    }
  }
}
walk('app');
if (out['/.']) { out['/'] = out['/.']; delete out['/.']; }
out.__default = git('.');
const body = `// Generated by scripts/gen-route-lastmod.mjs from git history. Do not edit by hand.\nexport const routeLastModified: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync('data/routeLastModified.ts', body);
console.log(Object.keys(out).length, 'routes');
